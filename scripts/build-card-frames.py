#!/usr/bin/env python3
"""Traces the playing-card frame artwork into vector paths.

Source: scripts/card-frames/card-heart.png and card-diamond.png (founder's
artwork, 2 Nov 2026: 1080 x 1080, the card 764 x 1078 px in the middle).
Output: src/features/editor/engine/card-frame-art.ts, used by the editor AND
the 300 DPI print renderer (`card-frame.ts`), so the frame is sharp at any
print size and both sides draw the very same outlines.

Only what is unique is traced; symmetry is applied when drawing:
- the inner frame: its TOP-LEFT QUARTER (drawn four times, mirrored);
- each suit: the TOP-LEFT pip with its drop (drawn twice, the second turned
  180 degrees round the card centre, like a real card).
The card itself (white, rounded, thin outline) and the photo window are plain
geometry in card-frame.ts.

Coordinates are source pixels relative to the card centre (539.5, 539.5).
Run: python3 scripts/build-card-frames.py   (needs Pillow, numpy, potracer)
"""
from pathlib import Path

import numpy as np
import potrace
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts/card-frames"
OUT = ROOT / "src/features/editor/engine/card-frame-art.ts"
CX = CY = 539.5
UP = 4  # trace at 4x for smooth curves


def redness(path: Path) -> np.ndarray:
    a = np.asarray(Image.open(path).convert("RGB")).astype(float)
    # 0 on white, 1 on the artwork red (197, 22, 24).
    return np.clip((a[:, :, 0] - a[:, :, 1]) / 175.0, 0, 1)


def trace(red: np.ndarray, x0: int, y0: int, x1: int, y1: int) -> str:
    """SVG path of the red shapes in the box, in card-centre coordinates."""
    crop = Image.fromarray((red[y0:y1, x0:x1] * 255).astype(np.uint8))
    big = crop.resize((crop.width * UP, crop.height * UP), Image.BICUBIC)
    # potracer traces the values below `blacklevel`: pass the red as dark.
    bm = potrace.Bitmap(np.asarray(big) < 128)
    plist = bm.trace(turdsize=8, alphamax=1.0, opticurve=True, opttolerance=0.2)

    def pt(p) -> str:
        x = p.x / UP + x0 - CX
        y = p.y / UP + y0 - CY
        return f"{x:.2f} {y:.2f}"

    parts = []
    for curve in plist:
        parts.append(f"M{pt(curve.start_point)}")
        for seg in curve.segments:
            if seg.is_corner:
                parts.append(f"L{pt(seg.c)}L{pt(seg.end_point)}")
            else:
                parts.append(f"C{pt(seg.c1)} {pt(seg.c2)} {pt(seg.end_point)}")
        parts.append("Z")
    return "".join(parts)


def main() -> None:
    heart = redness(SRC / "card-heart.png")
    diamond = redness(SRC / "card-diamond.png")
    # Inner frame quarter: from just outside its top-left corner to 2 px past
    # the centre lines, so mirrored copies overlap instead of leaving a seam.
    frame = trace(heart, 268, 82, 542, 542)
    # Top-left pips with their drops (well clear of the card outline).
    suits = {
        "heart": trace(heart, 172, 138, 262, 244),
        "diamond": trace(diamond, 172, 138, 262, 244),
    }
    lines = [
        "// Generated by scripts/build-card-frames.py from scripts/card-frames/*.png.",
        "// Do not edit by hand: change the artwork and re-run the script.",
        "",
        "/** Top-left quarter of the inner frame (drawn mirrored four times). */",
        f'export const CARD_FRAME_QUARTER =\n  "{frame}";',
        "",
        "/** Top-left pip and drop per suit (drawn twice, turned 180 degrees). */",
        "export const CARD_SUIT_PIP = {",
        *[f'  {k}:\n    "{v}",' for k, v in suits.items()],
        "} as const;",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


main()
